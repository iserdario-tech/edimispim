def rpc(method, params, id_=1):
    body = json.dumps({"jsonrpc": "2.0", "id": id_, "method": method, "params": params}).encode()
    req = urllib.request.Request(MCP, data=body, headers={"content-type": "application/json", "accept": "application/json, text/event-stream", "user-agent": "Mozilla/5.0 (edimispim price script; mmmikeshinoda@gmail.com)"})
    with urllib.request.urlopen(req, timeout=40) as r:
        return json.load(r)

def search(q, page=1):
    d = rpc("tools/call", {"name": "vkusvill_products_search", "arguments": {"q": q, "limit": 10, "page": page, "mode": "short"}})
    t = json.loads(d["result"]["content"][0]["text"])
    if not t.get("ok"): return []
    return t["data"]["items"]

W = re.compile(r"(\d+(?:[.,]\d+)?)\s*(кг|г|мл|л)\b", re.I)
N = re.compile(r"(\d+)\s*шт", re.I)
def grams(name, unit, product):
    n = name.replace("&nbsp;", " ")
    m = W.search(n)
    if m:
        v = float(m.group(1).replace(",", ".")); u = m.group(2).lower()
        return v * (1000 if u in ("кг", "л") else 1)
    if unit == "кг": return 1000                        # весовой товар: цена за килограмм
    m = N.search(n)
    if m and product in PIECE: return int(m.group(1)) * PIECE[product]
    if product == "яйца" and "шт" not in n.lower(): return 10 * PIECE["яйца"]   # коробка без числа — десяток
    return None

def stem(s):
    w = re.sub(r"[^а-яё ]", " ", s.lower()).split()
    w = [x for x in w if len(x) > 2]
    if not w: return s[:4]
    # четыре буквы: «гречка» и «гречневая» → «греч», «бананы» и «банан» → «бана»; у коротких — без последней: «яйца» → «яйц»
    return w[0][:4] if len(w[0]) >= 5 else w[0][:len(w[0]) - 1] if len(w[0]) == 4 else w[0]

def price_for(product):
    q = QUERY.get(product, product)
    if not q: return None, 0, "нет запроса"
    items = search(q)
    time.sleep(1.1)
    if len(items) >= 10:
        items += search(q, 2); time.sleep(1.1)
    st = stem(q)
    per100 = []
    for it in items:
        name = it["name"].replace("&nbsp;", " ")
        low = name.lower()
        # продукт — в первых двух словах названия: «Дорадо в оливковом масле» — не масло, «Напиток … кокосовое» — не молоко
        if st not in " ".join(low.split()[:2]): continue
        if product not in KEEP_STOP and STOP.search(low): continue
        g = grams(name, it.get("unit", ""), product)
        p = (it.get("price") or {}).get("current")
        # вес не в названии («Рукола, упаковка») — он есть в карточке товара; один лишний запрос на карточку
        if not g and p and len(per100) < 4:
            try:
                d = rpc("tools/call", {"name": "vkusvill_product_details", "arguments": {"id": int(it["id"])}})
                w = (json.loads(d["result"]["content"][0]["text"]).get("data") or {}).get("weight") or {}
                time.sleep(1.1)
                if w.get("value"): g = float(w["value"]) * (1000 if str(w.get("unit", "")).lower() in ("кг", "л") else 1)
            except Exception: g = None
        if not g or not p: continue
        per100.append(p / g * 100)
    if not per100: return None, len(items), "нет карточек с весом"
    per100.sort()
    # нижний квартиль всегда: при 2–4 карточках это самая дешёвая или вторая — «обычный продукт»,
    # медиана на четырёх карточках давала банан по 94 ₽ из-за зефира и банана в шоколаде
    val = per100[len(per100) // 4]
    return round(val, 1), len(per100), "квартиль"

def read_prices():
    s = open(PRICES_TS, encoding="utf-8").read()
    block = s[s.index("export const PRICES"): s.index("\n};", s.index("export const PRICES"))]
    prices = dict((m.group(1), float(m.group(2))) for m in re.finditer(r'^\s*"([^"]+)":\s*([\d.]+)', block, re.M))
    ub = s[s.index("export const UNKNOWN_PRICE"): s.index("]);", s.index("export const UNKNOWN_PRICE"))]
    unknown = re.findall(r'"([^"]+)"', ub)
    return s, prices, unknown

def main():
    write = "--write" in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith("--")]
    s, prices, unknown = read_prices()
    names = only or (list(prices) + unknown)
    new, report = {}, []
    for i, n in enumerate(names, 1):
        try: val, cnt, how = price_for(n)
        except Exception as e: val, cnt, how = None, 0, f"ошибка {e}"
        old = prices.get(n)
        new[n] = val
        mark = ""
        if val and old: mark = f"{(val / old - 1) * 100:+.0f}%"
        report.append((n, old, val, cnt, how, mark))
        print(f"{i:3}/{len(names)} {n:28} {str(old):>7} → {str(val):>7}  {mark:>6}  [{cnt} {how}]", flush=True)
    found = sum(1 for v in new.values() if v)
    print(f"\nснято {found} из {len(names)}; не найдено: {', '.join(n for n, v in new.items() if not v)}")
    if not write: return
    # переписать значения в PRICES; продукты из UNKNOWN_PRICE с найденной ценой — в PRICES и прочь из UNKNOWN
    for n, v in new.items():
        if v is None: continue
        pat = re.compile(r'^(\s*"%s":\s*)[\d.]+' % re.escape(n), re.M)
        if pat.search(s):
            s = pat.sub(lambda m: f"{m.group(1)}{v}", s, count=1)
        else:
            s = s.replace("export const PRICES: Record<string, number> = {\n",
                          f'export const PRICES: Record<string, number> = {{\n  "{n}": {v},\n', 1)
            i = s.index("export const UNKNOWN_PRICE")
            s = s[:i] + re.sub(r'"%s",\s*' % re.escape(n), "", s[i:], count=1)
    s = re.sub(r'export const PRICES_DATE = "[^"]+"', f'export const PRICES_DATE = "{datetime.date.today().isoformat()}"', s)
    open(PRICES_TS, "w", encoding="utf-8").write(s)
    print("prices.ts переписан; дальше: npm test")

if __name__ == "__main__":
    main()
