const TOPICAL = /сон|сна|сну|сп[аи]т|спл[юи]|засып|просып|высып|подъ[её]м|отбо[йя]|дрем|кофе|чай|чаю|алкогол|вин[оа]|пив[оа]|ед[аыуе](?![а-я])|еда|съе|пищ|калори|ккал|бел[ок]|жир|углевод|клетчат|вес[аеуы]?(?![а-я])|похуд|диет|дефицит|голод|аппетит|перекус|завтрак|обед|ужин|сладк|сахар|десерт|рецепт|готови|блюд|порци|меню|тренир|спорт|вод[аыу](?![а-я])|мелатонин|устал|бодр|энерги|храп|апноэ|ноч|утр[ао]|вечер|магни|витамин|добавк|плато|срыв|пицц|торт|жарен|мяс|рыб|овощ|фрукт|молок|творог|йогурт|хлеб|каш|суп|салат/i;
export const isTopical = (messages: CoachTurn[]): boolean => TOPICAL.test(messages.slice(-3).map(m => m.content).join(" "));

export interface CoachTurn { role: "user" | "assistant"; content: string }

// Стрим ответа (SSE) — коуч «печатает» сразу, а не молчит ~15 сек.
export async function coachStream(args: {
  ai: Ai;
  groqKey?: string;
  messages: CoachTurn[];
  contextRU: string;
}): Promise<ReadableStream> {
  // Короткое напоминание рядом с вопросом: правила в начале длинного промпта модель слышит хуже
  const REMINDER = `ПЕРЕД ОТВЕТОМ: любой вопрос — по существу с первого слова; длина по вопросу; никаких «это не моя тема»,
«зависит от многих факторов», «обратись к врачу» вместо ответа; цифры про сон и еду — из базы, цели — из плана человека;
по-русски, на «ты», без ** и ###.`;
  const base = isTopical(args.messages) ? `${SYSTEM_RULES}\n\nБАЗА ЗНАНИЙ (выжимка научного обзора, 223 источника):\n${KNOWLEDGE}` : SYSTEM_RULES;
  const system = `${base}\n\nСЕЙЧАС У ЧЕЛОВЕКА ТАК:\n${args.contextRU}\n\n${REMINDER}`;
  const messages: ChatMsg[] = [{ role: "system", content: system }, ...args.messages];
  // Groq первым — три модели по очереди, у каждой свой минутный лимит; Cloudflare — запасной.
  // «Недоступен» человек видит только когда легли все; «подожди минуту» — когда все упёрлись в лимит.
  let busy = false;
  if (args.groqKey) {
    for (const model of GROQ_MODELS) {
      try { const s = await groqStream(args.groqKey, model, messages, 1500, 0.4); console.log("coach via groq", model); return s; }
      catch (e) { busy = e instanceof GroqError && e.status === 429; console.log("groq failed", model, String(e).slice(0, 160)); }
    }
  }
  try {
    console.log("coach via cloudflare");
    return (await args.ai.run(MODEL as keyof AiModels, {
      messages,
      // Потолок — не рамка, а страховка от бесконечного ответа: длину задаёт вопрос (см. промпт).
      max_tokens: 1500,
      temperature: 0.4, // ниже — меньше выдумок, держится базы
      stream: true,
    } as any)) as unknown as ReadableStream;
  } catch (e) {
    if (busy) throw new CoachBusy();
    throw e;
  }
}

/** Все провайдеры упёрлись в минутный лимит: это «подожди», а не «сломалось». */
export class CoachBusy extends Error { constructor() { super("busy"); } }
