export interface CoachTurn { role: "user" | "assistant"; content: string }

// Стрим ответа (SSE от Workers AI) — коуч «печатает» сразу, а не молчит ~15 сек.
export async function coachStream(args: {
  ai: Ai;
  messages: CoachTurn[];
  contextRU: string;
}): Promise<ReadableStream> {
  /*
   * Напоминание о стиле идёт ПОСЛЕ базы знаний, а не только перед ней.
   *
   * База занимает почти пять тысяч токенов, и правила, оставшиеся далеко в начале,
   * она собой заглушает: модель исправно выдавала «это вопрос не про сон и еду, но я
   * отвечу» и пять предложений воды. Одно и то же требование, повторённое рядом с
   * вопросом, работает заметно лучше — это дешевле смены модели.
   */
  const REMINDER = `ПЕРЕД ОТВЕТОМ ПРОВЕРЬ СЕБЯ:
- Отвечай на любой вопрос полно и по существу. Длина — по вопросу: простое — коротко,
  сложное (объяснить, сравнить, план, текст, код) — столько, сколько нужно, абзацами и списками.
- Первое слово — уже по существу. Никаких «это сложный вопрос», «давай разберёмся»,
  «лучше проконсультироваться со специалистом» вместо ответа.
- НИКОГДА не рассуждай о том, твоя это тема или нет, и не упоминай сон и питание, если
  спросили о другом. Фразы вроде «это не про сон и еду», «не связано напрямую с питанием»,
  «но я могу дать совет» запрещены в любой формулировке. Спросили про ипотеку — первое
  слово ответа про ипотеку.
- Никаких «зависит от многих факторов» и «взвесь все за и против»: назови то, что решает дело.
- Числа про сон и еду — только из базы выше; калории, белок, дефицит, кофе и отбой — из плана человека.
- По-русски и на «ты»; термины и слова на других языках — где нужны. Без **, ### и таблиц.
- Не пересказывай вопрос («ты хочешь знать…») — сразу ответ.
- Спросили «можно ли» — первое слово «да» или «нет», и это «да/нет» должно совпадать с планом человека.`;
  const system = `${SYSTEM_RULES}\n\nСЕЙЧАС У ЧЕЛОВЕКА ТАК:\n${args.contextRU}\n\n${REMINDER}`;
  return (await args.ai.run(MODEL as keyof AiModels, {
    messages: [{ role: "system", content: system }, ...args.messages],
    // Потолок — не рамка, а страховка от бесконечного ответа: длину задаёт вопрос (см. промпт).
    // Было 350 — обрубало любое объяснение длиннее четырёх предложений (Сердар: «отвечай нормально»).
    max_tokens: 1500,
    temperature: 0.4, // ниже — меньше выдумок, держится базы
    stream: true,
  } as any)) as unknown as ReadableStream;
}
