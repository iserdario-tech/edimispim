/**
 * Короткий отклик на подтверждающее действие: отметка ночи, галочка в покупках, «съел».
 *
 * Vibration API есть не везде — в Safari на iOS его нет вовсе, и это нормально: там,
 * где отклика нет, просто ничего не происходит. Поэтому ни проверок возможностей,
 * ни запасных путей: одно необязательное обращение и молчаливый отказ.
 *
 * Длительность намеренно крошечная. Это подтверждение, а не уведомление.
 */
export const tap = (ms = 10): void => {
  try { navigator.vibrate?.(ms); } catch { /* отклика нет — и ладно */ }
};
