/** По составу ищем только «главное» блюда — мясо, рыбу, крупы: яйцо в тесте или
 *  томатная паста в соусе не делают блюдо омлетом или макаронами. */
const BY_INGREDIENT = new Set(["chicken", "turkey", "beef", "pork", "salmon", "whitefish", "fish", "seafood",
  "buckwheat", "rice", "beans", "potato", "mushrooms", "tofu", "vegetables"]);

/** Запасные варианты: если снимка нужного типа нет, берём ближайший по смыслу. */
const FALLBACK: Record<string, string[]> = {
  turkey: ["chicken"],
  borscht: ["soup"],
  wrap: ["taco"],
};

const BY_MEAL: Record<string, string> = {
  breakfast: "porridge", lunch: "soup", dinner: "chicken", dessert: "dessert", snack: "nuts",
};

/** Какой снимок показать для блюда. Пусто не возвращает никогда: картинка есть всегда. */
export function photoFor(recipe: Pick<Recipe, "name" | "meal_type" | "ingredients">): Photo {
  const kinds: string[] = [];
  const byName = RULES.find(([re]) => re.test(recipe.name))?.[1];
  const ings = (recipe.ingredients ?? []).map(i => i.name).join(" ");
  // у сладкого и перекусов состав не показателен: рисовая мука не делает оладьи рисом
  const mainMeal = ["breakfast", "lunch", "dinner"].includes(recipe.meal_type);
  const byIngredient = byName || !mainMeal ? undefined
    : RULES.find(([re, kind]) => BY_INGREDIENT.has(kind) && re.test(ings))?.[1];
  const found = byName ?? byIngredient;
  if (found) kinds.push(found);
  kinds.push(...(FALLBACK[kinds[0] ?? ""] ?? []));
  kinds.push(BY_MEAL[recipe.meal_type] ?? "chicken", "chicken");
  for (const k of kinds) if (PHOTOS[k]) return PHOTOS[k]!;
  return Object.values(PHOTOS)[0]!;
}

/** Путь к файлу для вёрстки. Относительный: приложение живёт в подпапке, и абсолютный
 *  «/food/…» искал бы картинки в корне домена, где их нет. */
export const photoUrl = (p: Photo): string => `food/${p.file}`;
