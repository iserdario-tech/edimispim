/**
 * Продукты, по которым выдача магазина не даёт вменяемой цены.
 *
 * По «банану» и «яблоку» после отсева переработки остаются банановые кексы и бананы
 * в шоколаде, по «стейку тунца» — только консервы и котлеты: цифра получилась бы враньём.
 * «Овощи» и «свежие овощи» — вообще не товар, а описание. Такие позиции не участвуют
 * в подсчёте, и интерфейс прямо перечисляет их под суммой: значит, выйдет дороже.
 */
export const UNKNOWN_PRICE = new Set([
  "банан", "банан замороженный", "яблоко", "вяленые томаты",
  "кус-кус", "натуральный йогурт", "яичные белки", "сироп топинамбура", "стейк тунца", "апельсин цедра",
  "свинина нежирная", "овощи", "свежие овощи",
  // по чернике и желатину выдача не отдаёт ни одной подходящей карточки
  "черника", "желатин", "кедровые орехи",
]);

export const priceFor = (name: string): number | undefined =>
  PRICES[name.toLowerCase().trim()];

/**
 * Стоимость количества продукта. `null` — цена неизвестна, а не ноль.
 *
 * Штучные продукты раньше не считались вовсе («штучный вес неизвестен»), и яйца —
 * а они почти в каждом втором рецепте — просто выпадали из суммы недели. Средний вес
 * штуки известен (`PIECE_GRAMS`), поэтому считаем через него; для незнакомых штучных
 * продуктов `gramsOf` берёт 60 г, и это по-прежнему гадание — такие продукты держим
 * в `UNKNOWN_PRICE`.
 */
export function costOf(name: string, qty: number, unit: string): number | null {
  const per100 = priceFor(name);
  if (per100 === undefined) return null;
  return Math.round((per100 * gramsOf(name, qty, unit)) / 100);
}

/** Насколько полон расчёт: сколько позиций посчитано по реальным ценам. */
export function coverage(names: string[]): { known: number; total: number } {
  const uniq = [...new Set(names.map(n => n.toLowerCase().trim()))];
  return { known: uniq.filter(n => PRICES[n] !== undefined).length, total: uniq.length };
}
